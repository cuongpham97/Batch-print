export function downloadBatFile(filename: string, content: string): void {
  const normalizedName = filename.trim().toLowerCase().endsWith('.bat')
    ? filename.trim()
    : `${filename.trim() || 'InHangLoat'}.bat`;

  // Ensure Windows CRLF and UTF-8 WITHOUT BOM (cmd.exe chokes on UTF-8 BOM)
  const crlfContent = content.replace(/\r?\n/g, '\r\n');
  const encoder = new TextEncoder();
  const bytes = encoder.encode(crlfContent);

  const blob = new Blob([bytes], { type: 'application/octet-stream' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = normalizedName;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
