export interface ResolvedPrintDecision {
  effectivePaperSize: PaperSize;
  effectiveOrientation: 'Portrait' | 'Landscape';
  effectiveDuplex: DuplexMode;
  duplexReason: string;
}

export function resolveEffectiveRule(
  profile: DocTypeProfile,
  detectedOrientation: 'Portrait' | 'Landscape'
): ResolvedPrintDecision {
  const effectivePaperSize: PaperSize = profile.defaultPaperSize;

  const effectiveOrientation: 'Portrait' | 'Landscape' =
    profile.orientationMode === 'ForcePortrait'
      ? 'Portrait'
      : profile.orientationMode === 'ForceLandscape'
        ? 'Landscape'
        : detectedOrientation;

  let effectiveDuplex: DuplexMode = 'OneSided';
  let duplexReason = 'In 1 mặt';

  if (profile.defaultSides === 'TwoSided') {
    if (profile.duplexStrategy === 'FixedLongEdge') {
      effectiveDuplex = 'TwoSidedLongEdge';
      duplexReason = 'Lật cạnh dài';
    } else if (profile.duplexStrategy === 'FixedShortEdge') {
      effectiveDuplex = 'TwoSidedShortEdge';
      duplexReason = 'Lật cạnh ngắn';
    } else if (profile.duplexStrategy === 'PortraitLongLandscapeShort') {
      effectiveDuplex =
        effectiveOrientation === 'Portrait' ? 'TwoSidedLongEdge' : 'TwoSidedShortEdge';
      duplexReason =
        effectiveOrientation === 'Portrait'
          ? 'Dọc -> Cạnh dài'
          : 'Ngang -> Cạnh ngắn';
    } else if (profile.duplexStrategy === 'PortraitShortLandscapeLong') {
      effectiveDuplex =
        effectiveOrientation === 'Portrait' ? 'TwoSidedShortEdge' : 'TwoSidedLongEdge';
      duplexReason =
        effectiveOrientation === 'Portrait'
          ? 'Dọc -> Cạnh ngắn'
          : 'Ngang -> Cạnh dài';
    } else if (profile.duplexStrategy === 'FileDefault') {
      effectiveDuplex = 'FileDefault';
      duplexReason = 'Mặc định của file';
    }
  }

  return {
    effectivePaperSize,
    effectiveOrientation,
    effectiveDuplex,
    duplexReason,
  };
}

function parseCustomExtensions(raw?: string): string[] {
  if (!raw || !raw.trim()) return [];
  const result: string[] = [];
  for (const token of raw.split(/[\s,;]+/)) {
    const clean = token.trim().toLowerCase();
    if (!clean) continue;
    const ext = clean.startsWith('.') ? clean : `.${clean}`;
    if (!result.includes(ext)) result.push(ext);
  }
  return result;
}

export function collectExtensionsList(config: PrintConfig): string[] {
  const list: string[] = [];
  const p = config.docProfiles;
  if (p.word.enabled) list.push('.docx', '.doc', '.rtf');
  if (p.excel.enabled) list.push('.xlsx', '.xls', '.xlsm');
  if (p.images.enabled) list.push('.jpg', '.jpeg', '.jfif', '.png', '.bmp', '.tif', '.tiff', '.gif', '.webp');
  if (p.pdf.enabled) list.push('.pdf');
  if (p.text.enabled) list.push('.txt', '.log', '.csv');
  if (p.other.enabled) {
    for (const ext of parseCustomExtensions(p.other.customExtensions)) {
      if (!list.includes(ext)) list.push(ext);
    }
  }
  return list;
}

function escapeBatchValue(value: string): string {
  return value.replace(/"/g, '').replace(/%/g, '%%');
}

function escapePsSingleQuoted(value: string): string {
  return value.replace(/'/g, "''");
}

function formatProfilePsEntry(id: DocTypeId, prof: DocTypeProfile): string {
  const copies = Math.max(1, Math.min(99, Math.round(prof.copies || 1)));
  const maxPages = Math.max(1, Math.min(9999, Math.round(prof.maxPagesLimit || 10)));
  const sumatraPath = escapePsSingleQuoted((prof.sumatraCustomPath || '').trim());
  const portM = resolveEffectiveMarginsMm(prof.margins, 'Portrait');
  const landM = resolveEffectiveMarginsMm(prof.margins, 'Landscape');
  const mMode = portM ? prof.margins.mode : 'Default';
  const mpT = portM ? portM.top : 0;
  const mpB = portM ? portM.bottom : 0;
  const mpL = portM ? portM.left : 0;
  const mpR = portM ? portM.right : 0;
  const mlT = landM ? landM.top : 0;
  const mlB = landM ? landM.bottom : 0;
  const mlL = landM ? landM.left : 0;
  const mlR = landM ? landM.right : 0;
  const wordSkipBlank = prof.wordSkipBlankPages ? 'true' : 'false';
  const excelSheetMode = prof.excelSheetMode || 'AllSheets';
  const excelPrintScope = prof.excelPrintScope || 'EntireSheet';
  const excelFitMode = prof.excelFitMode || 'None';
  const excelAutoLand = prof.excelAutoLandscapeByCols ? 'true' : 'false';
  const excelColThreshold = Math.max(1, Math.min(200, Math.round(prof.excelLandscapeColThreshold || 7)));
  const excelSkipBlank = prof.excelSkipBlankAreas ? 'true' : 'false';
  const excelSkipBlankSheets = prof.excelSkipBlankSheets ? 'true' : 'false';
  return `    ${id} = @{ Enabled=$${prof.enabled ? 'true' : 'false'}; Paper='${prof.defaultPaperSize}'; Sides='${prof.defaultSides}'; Strategy='${prof.duplexStrategy}'; Orient='${prof.orientationMode}'; Scale='${prof.scaleMode}'; MarginMode='${mMode}'; MPTop=${mpT}; MPBottom=${mpB}; MPLeft=${mpL}; MPRight=${mpR}; MLTop=${mlT}; MLBottom=${mlB}; MLLeft=${mlL}; MLRight=${mlR}; Copies=${copies}; Engine='${prof.engine}'; OverPageAction='${prof.overPageAction}'; MaxPages=${maxPages}; WordSkipBlank=$${wordSkipBlank}; ExcelSheet='${excelSheetMode}'; ExcelScope='${excelPrintScope}'; ExcelFit='${excelFitMode}'; ExcelAutoLand=$${excelAutoLand}; ExcelColThreshold=${excelColThreshold}; ExcelSkipBlank=$${excelSkipBlank}; ExcelSkipBlankSheets=$${excelSkipBlankSheets}; SumatraPath='${sumatraPath}' }`;
}

